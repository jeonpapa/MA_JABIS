export function translateUi(text: string): string | null {
  const key = text.trim();
  if (!key || !/[\uac00-\ud7a3]/.test(key)) return null;
  const hit = UI_EN[key];
  if (hit !== undefined) return text.replace(key, hit);
  for (const [re, fn] of UI_EN_PATTERNS) {
    const m = key.match(re);
    if (m) return text.replace(key, fn(...m));
  }
  // '약가제도 개편·신약 접근성' 처럼 사전 항목이 '·' 로 이어진 문구 — 모든 조각을 알 때만
  if (key.includes('·')) {
    const parts = key.split(/\s*·\s*/);
    if (parts.length > 1 && parts.every(x => x && UI_EN[x] !== undefined)) return text.replace(key, parts.map(x => UI_EN[x].trim()).join(' · '));
  }
  // '🇩🇪 독일' 처럼 한글 없는 머리 + 사전 항목
  const lead = key.match(/^([^\uac00-\ud7a3\s]+) (.+)$/);
  if (lead && UI_EN[lead[2]] !== undefined) return text.replace(key, `${lead[1]} ${UI_EN[lead[2]].trim()}`);
  return null;
}
